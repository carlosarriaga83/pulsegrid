class SSD1306_I2C:
    def __init__(self, width, height, i2c, addr=0x3C):
        self.width = width
        self.height = height
        self.i2c = i2c
        self.addr = addr
        self.buffer = bytearray(self.height * self.width // 8)
        self.framebuf = framebuf.FrameBuffer(self.buffer, self.width, self.height, framebuf.MONO_VLSB)
        for command in (
            (0x81, 0xFF), (0xA4,), (0xA6,), (0xAE,),
            (0x20, 0x00), (0x40,), (0xA1,), (0xC8,),
            (0xA8, self.height - 1), (0xD3, 0x00),
            (0xDA, 0x02 if self.height == 32 else 0x12),
            (0xD5, 0x80), (0xD9, 0xF1), (0xDB, 0x30),
            (0x8D, 0x14), (0xAF,),
        ):
            self._write_command(*command)
        self.fill(0)
        self.show()

    def _write_command(self, *commands):
        self.i2c.writeto(self.addr, b"\x00" + bytes(commands))

    def fill(self, color):
        self.framebuf.fill(color)

    def text(self, text, x, y, color=1, scale=1):
        x_position = x
        for character in text.upper():
            glyph = FONT_5X7.get(character, FONT_5X7[" "])
            for row, pixels in enumerate(glyph):
                for column, pixel in enumerate(pixels):
                    if pixel == "1":
                        self.framebuf.fill_rect(x_position + column * scale, y + row * scale, scale, scale, color)
            x_position += 6
            x_position += 6 * (scale - 1)

    def show(self):
        self._write_command(0x21, 0, self.width - 1)
        self._write_command(0x22, 0, self.height // 8 - 1)
        self.i2c.writeto(self.addr, b"\x40" + self.buffer)